type NamespaceEmitters = ReadonlyMap<string, TsNamespaceEmitter>;

/** Field/condition references can cycle. Only a base class must exist at declaration time. */
function inheritanceComponents(
  walks: ReadonlyMap<string, NamespaceWalkResult>,
  emitters: NamespaceEmitters
): string[][] {
  const parents = new Map<string, Set<string>>();
  for (const [namespace, walk] of walks) {
    for (const data of walk.dataByName.values()) {
      const parent = data.superType?.ref;
      const owner = isData(parent) ? getElementNamespace(parent) : undefined;
      if (!owner || owner === namespace || !walks.has(owner)) continue;
      const dependencies = parents.get(namespace) ?? new Set<string>();
      dependencies.add(owner);
      parents.set(namespace, dependencies);
    }
  }
  if (!parents.size) return [];
  const nodes = [...walks.keys()].sort();
  const edges = new Map(
    nodes.map((name) => [
      name,
      [...emitters.get(name)!.moduleImports.keys()].filter((dependency) => walks.has(dependency))
    ])
  );
  return stronglyConnectedComponents({ nodes, edges })
    .filter((component) => {
      if (component.length < 2) return false;
      const members = new Set(component);
      return component.some((name) => [...(parents.get(name) ?? [])].some((parent) => members.has(parent)));
    })
    .map((component) => component.sort())
    .sort((a, b) => a[0]!.localeCompare(b[0]!));
}

function componentImports(emitters: NamespaceEmitters, namespace: string, registry: NamespaceRegistry): string[] {
  const imports = new Map<string, Set<string>>();
  for (const emitter of emitters.values()) {
    for (const [dependency, bindings] of emitter.moduleImports) {
      if (emitters.has(dependency)) continue;
      const symbols = imports.get(dependency) ?? new Set<string>();
      for (const binding of bindings) symbols.add(binding);
      imports.set(dependency, symbols);
    }
  }
  return buildCrossNsImportLines(imports, namespace, registry, '.js');
}

function orderedClasses(members: readonly TypeScriptComponentMember[]): string[] {
  const classes = new Map<Data, string>();
  for (const member of members) for (const [data, source] of member.classes) classes.set(data, source);
  const keys = new Map([...classes.keys()].map((data) => [data, getElementNamespace(data) + '.' + data.name]));
  const declarations = new Map([...classes].map(([data, source]) => [keys.get(data)!, source]));
  const edges = new Map(
    [...keys].map(([data, key]) => {
      const parent = data.superType?.ref;
      const dependency = isData(parent) ? keys.get(parent) : undefined;
      return [key, dependency === undefined ? [] : [dependency]];
    })
  );
  return topoSort({ nodes: [...declarations.keys()], edges }, new Set()).map((key) => declarations.get(key)!);
}

function emitComponent(
  namespace: string,
  emitters: NamespaceEmitters,
  registry: NamespaceRegistry,
  inline: boolean
): { output: GeneratorOutput; members: TypeScriptComponentMember[] } {
  const relativePath = getTargetRelativePath(namespace, 'typescript');
  const namespaces = [...emitters.keys()];
  const libraryHelpers = [...new Set([...emitters.values()].flatMap((emitter) => emitter.libraryHelpers))];
  const metadata = [...emitters.values()].some((emitter) => emitter.usesMetadata);
  const sections = [
    '// SPDX-License-Identifier: MIT',
    '// Generated by @rune-langium/codegen — do not edit',
    '// Shared module for namespaces: ' + namespaces.join(', '),
    '',
    ...typescriptRuntimePreamble(registry, namespace, libraryHelpers, metadata, inline),
    ...publicHelperExports(registry, inline ? null : undefined),
    ...componentImports(emitters, namespace, registry),
    ''
  ];
  const members = [...emitters.values()].map((emitter) => emitter.emitComponentMember(namespace));
  const output: GeneratorOutput = {
    relativePath,
    namespaces,
    content: '',
    diagnostics: [],
    funcs: [],
    sourceMap: [],
    projections: []
  };
  let lineOffset = sections.join('\n').split('\n').length;
  for (const { output: member } of members) {
    const content = member.content.trimEnd();
    output.sourceMap.push(
      ...member.sourceMap.map((entry) => ({ ...entry, outputLine: lineOffset + entry.outputLine }))
    );
    output.diagnostics.push(...member.diagnostics);
    output.funcs.push(...member.funcs.map((func) => ({ ...func, relativePath })));
    output.projections!.push(...(member.projections ?? []));
    sections.push(content);
    lineOffset += content.split('\n').length;
  }
  sections.push(...orderedClasses(members));
  output.content = sections.join('\n') + '\n';
  return { output, members };
}

function emitFacade(
  member: TypeScriptComponentMember,
  moduleNamespace: string,
  registry: NamespaceRegistry
): { output: GeneratorOutput; exports: ReadonlyMap<string, boolean> } {
  const { output, classes, exportNames } = member;
  const path = resolveImportPath(output.namespaces![0]!, moduleNamespace, registry) + '.js';
  const exports = new Map<string, boolean>();
  const names = [...typescriptModuleExports(output.content + [...classes.values()].join('\n'))].map(
    ([name, hasValue]) => {
      const exported = exportNames.get(name) ?? name;
      exports.set(exported, hasValue);
      return (hasValue ? '' : 'type ') + (name === exported ? name : name + ' as ' + exported);
    }
  );
  return {
    output: {
      ...output,
      content: [
        '// SPDX-License-Identifier: MIT',
        '// Generated by @rune-langium/codegen — do not edit',
        ...publicHelperExports(registry, path),
        'export { ' + names.join(', ') + " } from '" + path + "';",
        ''
      ].join('\n'),
      funcs: output.funcs.map((func) => ({
        ...func,
        exportName: exportNames.get(func.exportName ?? func.name) ?? func.exportName,
        ...(func.inputCheckExportName
          ? { inputCheckExportName: exportNames.get(func.inputCheckExportName) ?? func.inputCheckExportName }
          : {})
      })),
      sourceMap: []
    },
    exports
  };
}

/** Keep the public namespace modules while assembling eager declarations in dependency order. */
export class TypeScriptModelEmitter extends GenericModelEmitter<'typescript'> {
  constructor() {
    super(TsNamespaceEmitter, typescriptProfile);
  }

  protected override emitLayout(
    walks: ReadonlyMap<string, NamespaceWalkResult>,
    registry: NamespaceRegistry,
    options: GeneratorOptions,
    layout: ModelLayout
  ): GeneratorOutput[] {
    const inline = layout === 'per-namespace' && options.typescript?.inlineHelpers === true;
    const emitters = new Map(
      [...walks].map(([name, walk]) => [
        name,
        new TsNamespaceEmitter(walk, { ...options, suppressBoilerplate: !inline }, registry)
      ])
    );
    const groups = inheritanceComponents(walks, emitters);
    if (groups.length && layout === 'single-file') {
      const { output } = emitComponent('model', emitters, registry, false);
      return this.emitSingleFile([output], registry, output);
    }

    const inComponent = new Set(groups.flat());
    const modules = [...walks].flatMap(([name, walk]) =>
      inComponent.has(name) ? [] : [emitNamespaceDeclarations(walk, emitters.get(name)!)]
    );
    if (!groups.length) return inline ? modules : this.assembleNamespaces(walks, registry, layout, modules);

    const reserved = new Set([...walks.keys()].map((name) => name.toLowerCase()));
    const support: GeneratorOutput[] = [];
    const facadeExports = new Map<string, ReadonlyMap<string, boolean>>();
    let nextComponent = 1;
    for (const group of groups) {
      let namespace: string;
      do namespace = 'rune_component_' + nextComponent++;
      while (reserved.has(namespace));
      const component = emitComponent(
        namespace,
        new Map(group.map((name) => [name, emitters.get(name)!])),
        registry,
        inline
      );
      for (const member of component.members) {
        const facade = emitFacade(member, namespace, registry);
        modules.push(facade.output);
        facadeExports.set(facade.output.relativePath, facade.exports);
      }
      support.push({
        ...component.output,
        namespaces: undefined,
        diagnostics: [],
        funcs: [],
        projections: [],
        artifactRole: 'support'
      });
    }
    modules.sort((a, b) => a.relativePath.localeCompare(b.relativePath));
    return [
      ...modules,
      ...(layout === 'barrel' ? [makeTypeScriptBarrel(modules, registry, facadeExports)] : []),
      ...support,
      ...(inline ? [] : this.sharedArtifacts(modules, registry))
    ];
  }
}
