/** Restore keyword escapes to each segment of a normalized Rune identifier. */
export function escapeRuneIdentifier(name: string): string {
  return name
    .split('.')
    .map((segment) => (RESERVED_KEYWORDS.has(segment) ? `^${segment}` : segment))
    .join('.');
}
