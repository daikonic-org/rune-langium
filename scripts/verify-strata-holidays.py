"""Verify or deliberately regenerate the finite Strata calendar data and its target fixtures."""

import argparse
from datetime import date, timedelta
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
from lib.java_reference_oracle import verified_classpath

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "test/fixtures/third-party/cdm-business-calendars"
DATA = ROOT / "packages/project-runtime/src/curated-implementations/rune/strata-holiday-data.rosetta"
EPOCH = date(1970, 1, 1)


def read_calendars(classpath, center_codes):
    java = Path(os.environ.get("JAVA_BINARY", "java"))
    javac = java.with_name("javac")
    source = ROOT / "scripts/fixtures/StrataHolidayOracle.java"
    with tempfile.TemporaryDirectory() as temporary:
        classes = Path(temporary)
        input_file = classes / "center-codes"
        input_file.write_text("\n".join(center_codes) + "\n")
        subprocess.run([str(javac), "-cp", classpath, "-d", str(classes), str(source)], check=True)
        result = subprocess.run(
            [
                str(java), "-cp", os.pathsep.join([str(classes), classpath]),
                "com.opengamma.strata.basics.date.StrataHolidayOracle", str(input_file),
            ],
            capture_output=True, check=True, text=True, timeout=60,
        )
    calendars = {}
    for line in result.stdout.splitlines():
        center, first, last, weekends, holidays, working_days, digest = line.split("\t")
        calendars[center] = {
            "firstDay": int(first),
            "lastDay": int(last),
            "weekendWeekdays": [int(day) for day in weekends.split(",")],
            "holidays": [int(day) for day in holidays.split(",") if day],
            "workingDays": [int(day) for day in working_days.split(",") if day],
            "digest": digest,
        }
    return calendars


def rune_list(numbers):
    chunks = [", ".join(map(str, numbers[i:i + 20])) for i in range(0, len(numbers), 20)]
    return "[" + ",\n            ".join(chunks) + "]"


def calendar_pairs(first_day, dates):
    words = []
    index = 0
    while index < len(dates):
        offset = dates[index] - first_day
        gap = dates[index + 1] - dates[index] if index + 1 < len(dates) else 0
        if gap >= 100:
            gap = 0
        words.append(offset * 100 + gap)
        index += 2 if gap else 1
    return words


def rune_source(calendars):
    fields = ("firstDay", "lastDay", "weekendWeekdays", "holidays", "workingDays")
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Pradeep Mouli",
        "// Generated by scripts/verify-strata-holidays.py from Strata 2.12.78.",
        "// Strata data is covered by the bundled Apache 2.0 license and notice.",
        "namespace com.opengamma.strata.basics.date",
        'version "2.12.78"',
        "",
        "func PinnedHolidayCalendar:",
        "    inputs: center string (1..1)",
        "    output: calendar HolidayCalendar (1..1)",
        "",
        "    alias selected: center switch",
    ]
    for center, row in calendars.items():
        lines.append(f'        "{center}" then HolidayCalendar {{')
        for index, field in enumerate(fields):
            value = row[field]
            if field in ("holidays", "workingDays") and value:
                words = rune_list(calendar_pairs(row["firstDay"], value))
                rendered = f"UnpackCalendarDates({row['firstDay']}, {words})"
            else:
                rendered = rune_list(value) if isinstance(value, list) else str(value)
            comma = "," if index < len(fields) - 1 else ""
            lines.append(f"            {field}: {rendered}{comma}")
        lines.append("        },")
    lines += [
        "        default empty",
        "",
        "    condition SupportedBusinessCenter: selected exists",
        "    set calendar: selected",
    ]
    return "\n".join(lines) + "\n"


def expected_result(case, calendars):
    inputs = case["inputs"]
    if case["function"] == "BusinessCenterHolidays":
        row = calendars.get(inputs["businessCenter"])
        if row is None:
            return {"expectedError": "SupportedBusinessCenter"}
        return {"holidayCount": len(row["holidays"]), "holidayDigest": row["digest"]}

    period = inputs.get("period")
    dates = inputs.get("dates", [])
    if (period is not None) == bool(dates):
        return {"expectedError": "PeriodOrDates"}
    if period is not None:
        start = period.get("adjustedStartDate")
        end = period.get("adjustedEndDate")
        if not start or not end or start > end:
            return {"expectedError": "OrderedCalendarPeriod"}
        start, end = date.fromisoformat(start), date.fromisoformat(end)
        dates = [(start + timedelta(days=i)).isoformat() for i in range((end - start).days + 1)]
    days = [date.fromisoformat(value) for value in dates]
    ordinals = [(day - EPOCH).days for day in days]
    selected = []
    for center in dict.fromkeys(inputs["businessCenters"]):
        row = calendars.get(center)
        if row is None:
            return {"expectedError": "SupportedBusinessCenter"}
        selected.append(row)
    if any(min(ordinals) < row["firstDay"] or max(ordinals) > row["lastDay"] for row in selected):
        return {"expectedError": "HolidayCalendarCoverage"}
    expected = []
    for value, day, ordinal in zip(dates, days, ordinals):
        weekday = day.isoweekday()
        closed = any(
            ordinal in row["holidays"] or (weekday in row["weekendWeekdays"] and ordinal not in row["workingDays"])
            for row in selected
        ) if selected else weekday >= 6
        if closed:
            expected.append(value)
    return {"expected": expected} if expected else {"expectedError": "NonBusinessDatesRequired"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", type=Path, required=True)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((FIXTURE / "strata.json").read_text())
    classpath = verified_classpath(ROOT, manifest, args.cache_dir)
    resource = json.loads((FIXTURE / "resources/business-center-9-3.json").read_text())
    codes = sorted(entry["value"] for entry in resource["codes"])
    calendars = read_calendars(classpath, codes)
    if not calendars:
        raise SystemExit("No matching published business-center calendars")

    cases_path = FIXTURE / "cases.json"
    cases = json.loads(cases_path.read_text())
    reviewed_centers = {
        case["inputs"]["businessCenter"] for case in cases
        if case["function"] == "BusinessCenterHolidays" and case["inputs"]["businessCenter"] in calendars
    }
    if reviewed_centers != calendars.keys():
        raise SystemExit("Missing full-list expectations for a published calendar")
    updated_cases = [
        {**{key: case[key] for key in ("id", "function", "inputs")}, **expected_result(case, calendars)}
        for case in cases
    ]
    source = rune_source(calendars)
    if args.write:
        DATA.write_text(source)
        cases_path.write_text(json.dumps(updated_cases, indent=2) + "\n")
    elif source != DATA.read_text() or updated_cases != cases:
        raise SystemExit("The pinned Strata calendar source or expectations changed")
    count = sum(len(row["holidays"]) for row in calendars.values())
    print(f"Verified {len(calendars)} calendars, {count:,} holidays, and {len(cases)} target cases from Strata 2.12.78.")


if __name__ == "__main__":
    main()
